import AppKit
import Combine

/// Everything that was on the pasteboard at one moment: per pasteboard item,
/// every type and its data. Writing it back recreates the clipboard exactly,
/// formatting, file references and all.
typealias PasteboardSnapshot = [[NSPasteboard.PasteboardType: Data]]

/// One entry in the clipboard history.
struct ClipItem: Identifiable {
    enum Content {
        case text(String)
        /// A small preview for the list, and the full size in pixels.
        case image(thumbnail: NSImage, pixelSize: CGSize)
        /// Files copied in Finder, with the icon of the first one.
        case files([URL], icon: NSImage)
    }

    let id = UUID()
    let content: Content
    let date: Date
    /// The app that was in front when the item was copied.
    let appName: String?
    /// What gets put back on the clipboard when the item is picked.
    let snapshot: PasteboardSnapshot
    /// The same thing without formatting: the text, or the paths of the files.
    /// Nil for images.
    let plainText: String?

    var isImage: Bool {
        if case .image = content { return true }
        return false
    }

    var searchableText: String {
        switch content {
        case .text(let string): return string
        case .image: return "image picture screenshot"
        case .files(let urls, _): return "file " + urls.map(\.lastPathComponent).joined(separator: " ")
        }
    }

    /// True when both hold the same thing, whatever their dates.
    func hasSameContent(as other: ClipItem) -> Bool {
        switch (content, other.content) {
        case (.text(let a), .text(let b)): return a == b
        case (.files(let a, _), .files(let b, _)): return a == b
        case (.image, .image): return snapshot == other.snapshot
        default: return false
        }
    }
}

/// Clipboard history.
///
/// macOS has no "clipboard changed" notification, so the store checks the
/// pasteboard's change counter twice a second. The history is kept in memory
/// only and is gone when the app quits. Pinned clips are the exception: the
/// user asked for those to stay, so they are saved to a file.
final class ClipboardStore: ObservableObject {
    /// Pinned clips, in the order they were pinned. Shown first, never dropped.
    @Published private(set) var pinned: [ClipItem] = []
    /// The rest, newest first.
    @Published private(set) var items: [ClipItem] = []

    /// Clips older than this are forgotten. Pinned clips never are. Nil: keep them.
    var forgetAfter: TimeInterval? {
        didSet { forgetExpired() }
    }

    private let maxItems = 40
    /// Images are big and rarely needed far back, so only the latest few are kept.
    private let maxImages = 5

    private let pasteboard: NSPasteboard
    private let pinnedFile: URL?
    private var lastChangeCount = 0
    private var timer: Timer?
    /// The entry the clipboard currently holds, if any.
    private var currentItemID: UUID?

    /// Markers that password managers and similar apps put on the pasteboard
    /// to say "do not record this". See nspasteboard.org.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// ~/Library/Application Support/WinDummy/Pinned.plist
    static var defaultPinnedFile: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?
            .appendingPathComponent("WinDummy", isDirectory: true)
            .appendingPathComponent("Pinned.plist")
    }

    /// Tests pass a private pasteboard and their own file (or none), so they
    /// never touch the real clipboard or the user's pinned clips.
    init(pasteboard: NSPasteboard = .general, pinnedFile: URL? = ClipboardStore.defaultPinnedFile) {
        self.pasteboard = pasteboard
        self.pinnedFile = pinnedFile
        loadPinned()
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount

        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Puts an item back on the clipboard, so the next ⌘V pastes it.
    /// With `plainText`, only the bare text goes back: no formatting, and
    /// files become their paths.
    func copyToClipboard(_ item: ClipItem, plainText: Bool = false) {
        if plainText, let text = item.plainText {
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
        } else {
            Self.write(item.snapshot, to: pasteboard)
        }
        // This change is our own; do not record it as a new entry.
        lastChangeCount = pasteboard.changeCount
        currentItemID = item.id

        if let index = items.firstIndex(where: { $0.id == item.id }), index != 0 {
            let moved = items.remove(at: index)
            items.insert(moved, at: 0)
        }
    }

    /// Puts `string` on the clipboard just long enough for `paste` to use it,
    /// then puts back whatever was there before. None of it shows up in the history.
    ///
    /// Pasting works in every app, unlike typing with synthetic key events,
    /// which some apps (Electron ones among them) ignore.
    func pasteTemporarily(_ string: String, paste: @escaping () -> Void) {
        let saved = Self.snapshot(of: pasteboard, sizeLimit: nil)
        let savedItemID = currentItemID

        pasteboard.clearContents()
        pasteboard.setString(string, forType: .string)
        lastChangeCount = pasteboard.changeCount
        let ourChange = lastChangeCount

        paste()

        // The app receiving ⌘V reads the clipboard when it handles the key
        // press, which is quick but not instant. Give it a moment.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) { [weak self] in
            guard let self else { return }
            // Something new was copied in the meantime; leave it alone.
            guard self.pasteboard.changeCount == ourChange else { return }

            Self.write(saved, to: self.pasteboard)
            self.lastChangeCount = self.pasteboard.changeCount
            self.currentItemID = savedItemID
        }
    }

    /// Removes one entry, pinned or not. If the clipboard still holds that
    /// entry, the clipboard is emptied too, so a deleted code or password
    /// cannot be pasted by accident afterwards.
    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if pinned.contains(where: { $0.id == item.id }) {
            pinned.removeAll { $0.id == item.id }
            savePinned()
        }

        // An unchanged counter means nothing has been copied since we last looked.
        if currentItemID == item.id, pasteboard.changeCount == lastChangeCount {
            pasteboard.clearContents()
            lastChangeCount = pasteboard.changeCount
            currentItemID = nil
        }
    }

    /// Clears the history. Pinned clips stay.
    func clear() {
        items.removeAll()
    }

    // MARK: - Pinning

    func isPinned(_ item: ClipItem) -> Bool {
        pinned.contains { $0.id == item.id }
    }

    func togglePin(_ item: ClipItem) {
        if let index = pinned.firstIndex(where: { $0.id == item.id }) {
            // Back into the history, at the top.
            let unpinned = pinned.remove(at: index)
            items.insert(unpinned, at: 0)
            trimHistory()
        } else {
            items.removeAll { $0.id == item.id }
            pinned.append(item)
        }
        savePinned()
    }

    // MARK: - Recording

    /// Records the clipboard if it changed. Called by the timer; internal for tests.
    func poll() {
        forgetExpired()

        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        // Until proven otherwise, the clipboard holds something we do not record.
        currentItemID = nil

        let types = pasteboard.types ?? []
        if types.contains(where: { ignoredTypes.contains($0.rawValue) }) {
            return
        }

        let appName = NSWorkspace.shared.frontmostApplication?.localizedName
        if let item = Self.makeItem(from: pasteboard, date: Date(), appName: appName) {
            add(item)
        }
    }

    private func add(_ item: ClipItem) {
        // Copying something that is pinned does not add it to the history again.
        if let match = pinned.first(where: { $0.hasSameContent(as: item) }) {
            currentItemID = match.id
            return
        }

        // Copying the same thing again moves it to the top instead of duplicating it.
        items.removeAll { $0.hasSameContent(as: item) }
        items.insert(item, at: 0)
        currentItemID = item.id
        trimHistory()
    }

    private func trimHistory() {
        let imageIDs = items.filter(\.isImage).map(\.id)
        if imageIDs.count > maxImages {
            let dropped = Set(imageIDs.dropFirst(maxImages))
            items.removeAll { dropped.contains($0.id) }
        }
        if items.count > maxItems {
            items.removeLast(items.count - maxItems)
        }
    }

    private func forgetExpired() {
        guard let forgetAfter else { return }
        let cutoff = Date().addingTimeInterval(-forgetAfter)
        // Check first: assigning to `items` redraws the list even if nothing changed.
        if items.contains(where: { $0.date < cutoff }) {
            items.removeAll { $0.date < cutoff }
        }
    }

    // MARK: - Turning pasteboard contents into an entry

    /// Pasteboard types larger than this are left out of a snapshot. Office
    /// apps, for one, add big bitmap renderings next to the text.
    private static let maxTypeSize = 5_000_000

    static func makeItem(from pasteboard: NSPasteboard, date: Date, appName: String?) -> ClipItem? {
        // Files first: Finder also puts the file names on the pasteboard as
        // text, and we do not want to mistake those for copied text.
        makeFilesItem(from: pasteboard, date: date, appName: appName)
            ?? makeTextItem(from: pasteboard, date: date, appName: appName)
            ?? makeImageItem(from: pasteboard, date: date, appName: appName)
    }

    private static func makeFilesItem(from pasteboard: NSPasteboard, date: Date, appName: String?) -> ClipItem? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
              !urls.isEmpty else { return nil }

        return ClipItem(
            content: .files(urls, icon: NSWorkspace.shared.icon(forFile: urls[0].path)),
            date: date,
            appName: appName,
            snapshot: snapshot(of: pasteboard, sizeLimit: maxTypeSize),
            plainText: urls.map(\.path).joined(separator: "\n")
        )
    }

    private static func makeTextItem(from pasteboard: NSPasteboard, date: Date, appName: String?) -> ClipItem? {
        guard let string = pasteboard.string(forType: .string),
              !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }

        var snapshot = snapshot(of: pasteboard, sizeLimit: maxTypeSize)
        if snapshot.isEmpty {
            snapshot = [[.string: Data(string.utf8)]]
        }
        return ClipItem(content: .text(string), date: date, appName: appName, snapshot: snapshot, plainText: string)
    }

    /// Keeps the image as one PNG instead of everything the source app offered.
    /// A screenshot of a large screen is around 60 MB as TIFF, a few MB as PNG.
    private static func makeImageItem(from pasteboard: NSPasteboard, date: Date, appName: String?) -> ClipItem? {
        guard let png = pasteboard.data(forType: .png) ?? NSImage(pasteboard: pasteboard).flatMap(pngData),
              let rep = NSBitmapImageRep(data: png) else { return nil }

        let pixelSize = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        return ClipItem(
            content: .image(thumbnail: thumbnail(of: rep, pixelSize: pixelSize), pixelSize: pixelSize),
            date: date,
            appName: appName,
            snapshot: [[.png: png]],
            plainText: nil
        )
    }

    // MARK: - Pinned clips on disk

    private func savePinned() {
        guard let pinnedFile else { return }
        let entries: [[String: Any]] = pinned.map { item in
            var entry: [String: Any] = [
                "date": item.date,
                "snapshot": item.snapshot.map { contents in
                    Dictionary(uniqueKeysWithValues: contents.map { ($0.key.rawValue, $0.value) })
                },
            ]
            entry["app"] = item.appName
            return entry
        }
        do {
            try FileManager.default.createDirectory(at: pinnedFile.deletingLastPathComponent(), withIntermediateDirectories: true)
            let data = try PropertyListSerialization.data(fromPropertyList: entries, format: .binary, options: 0)
            try data.write(to: pinnedFile, options: .atomic)
        } catch {
            NSLog("WinDummy: could not save pinned clips: \(error.localizedDescription)")
        }
    }

    /// Rebuilds each pinned clip by putting its snapshot on a scratch
    /// pasteboard and reading it with the same code that reads the clipboard.
    private func loadPinned() {
        guard let pinnedFile,
              let data = try? Data(contentsOf: pinnedFile),
              let entries = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [[String: Any]]
        else { return }

        let scratch = NSPasteboard.withUniqueName()
        defer { scratch.releaseGlobally() }

        pinned = entries.compactMap { entry in
            guard let rawSnapshot = entry["snapshot"] as? [[String: Data]] else { return nil }
            let snapshot: PasteboardSnapshot = rawSnapshot.map { contents in
                Dictionary(uniqueKeysWithValues: contents.map { (NSPasteboard.PasteboardType($0.key), $0.value) })
            }
            Self.write(snapshot, to: scratch)
            return Self.makeItem(from: scratch, date: entry["date"] as? Date ?? Date(), appName: entry["app"] as? String)
        }
    }

    // MARK: - Pasteboard helpers

    /// Copies every type of every pasteboard item. With a `sizeLimit`, types
    /// larger than that are left out.
    private static func snapshot(of pasteboard: NSPasteboard, sizeLimit: Int?) -> PasteboardSnapshot {
        (pasteboard.pasteboardItems ?? []).compactMap { item in
            var contents: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                if let sizeLimit, data.count > sizeLimit { continue }
                contents[type] = data
            }
            return contents.isEmpty ? nil : contents
        }
    }

    private static func write(_ snapshot: PasteboardSnapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let items = snapshot.map { contents -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in contents {
                item.setData(data, forType: type)
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
    }

    private static func pngData(from image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    /// A preview small enough for a list row (it is drawn at most 110 × 56 points).
    private static func thumbnail(of rep: NSBitmapImageRep, pixelSize: CGSize) -> NSImage {
        let maxSide: CGFloat = 240
        let scale = min(1, maxSide / max(pixelSize.width, pixelSize.height, 1))
        let size = NSSize(width: max(1, pixelSize.width * scale), height: max(1, pixelSize.height * scale))

        let thumbnail = NSImage(size: size)
        thumbnail.lockFocus()
        NSGraphicsContext.current?.imageInterpolation = .high
        rep.draw(in: NSRect(origin: .zero, size: size))
        thumbnail.unlockFocus()
        return thumbnail
    }
}
